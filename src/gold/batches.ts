// 정답 100건을 원문 쓰는 이 넷에게 나눠 준다. 묶음마다 25건, 연습과 안 여는 세트가 섞이고 꼴이 고르다.
import path from 'node:path';
import { TYPE_LABELS } from '@/contract/fields';
import { GOLD_STYLES, STYLE_LABELS } from '@/contract/eval-types';
import type { GoldSpec } from './spec';

export const BATCH_COUNT = 4;

export interface WriterBatch {
  batch: number;
  /** 다 쓴 원문을 적을 파일. 조립기(assemble.ts 의 readWritten)가 읽는 자리와 같다. */
  output_path: string;
  /** 출력 꼴 */
  output_format: string;
  docs: (GoldSpec & { type_label: string; style_label: string })[];
}

export const GUIDE_NAME = 'WRITER-GUIDE.md';
export const batchInputName = (n: number) => `batch-${n}.json`;
/** 써 온 원문이 놓이는 자리(작업 폴더에서 본 길). 묶음 파일의 output_path, 안내 글, 조립기가 모두 이것 하나를 쓴다. */
export const batchOutputName = (n: number) => `out/batch-${n}.json`;
export const batchOutputPath = (dir: string, n: number) => path.join(dir, batchOutputName(n));

/** 꼴 × 묶음(연습/안 여는 세트)별로 돌아가며 나눠서, 묶음마다 꼴과 비율이 같게 한다. */
export function splitBatches(specs: readonly GoldSpec[], dir: string): WriterBatch[] {
  const batches: WriterBatch[] = Array.from({ length: BATCH_COUNT }, (_, i) => ({
    batch: i + 1,
    output_path: batchOutputPath(dir, i + 1),
    output_format: '[{"id": "dev-001", "content": "원문 글"}, …] — 이 묶음의 문서 25건 전부, JSON 배열 하나. 다른 열쇠나 설명은 넣지 않는다.',
    docs: [],
  }));
  let turn = 0;
  for (const style of GOLD_STYLES) {
    for (const split of ['dev', 'test'] as const) {
      const group = specs.filter((s) => s.style === style && s.split === split).sort((a, b) => a.id.localeCompare(b.id));
      for (const spec of group) {
        const batch = batches[turn % BATCH_COUNT] as WriterBatch;
        batch.docs.push({ ...spec, type_label: TYPE_LABELS[spec.type], style_label: STYLE_LABELS[spec.style] });
        turn += 1;
      }
    }
  }
  return batches;
}

/** 원문 쓰는 이가 읽는 안내. dir 은 이번 차례의 작업 폴더다. */
export function writerGuide(dir: string): string {
  const input = (n: number | string) => path.join(dir, `batch-${n}.json`);
  const output = (n: number | string) => path.join(dir, `out/batch-${n}.json`);
  return `# 원문 쓰기 안내 (둘째 차례)

가상 마켓 "응원장터"에 공급처가 보내는 상품 소개 글을 쓴다. 정답(칸별 값)은 이미 정해져 있다.
할 일은 **그 정답이 담긴 원문**을 쓰는 것이다. 정답을 바꾸지 않는다.

이번 차례에 달라진 것: 값을 적는 **표기가 건마다 다르다.** 같은 크기라도 어떤 건은 "가로 8m × 세로 4.5m", 어떤 건은 "8000mm*4500mm", 어떤 건은 "8X4.5"(단위는 표 머리에)다. 실제 공급처 자료가 그렇게 제각각이기 때문이다. 어느 표기를 쓸지는 묶음 파일에 건마다 정해져 있다. **표기는 고르지 않는다. 적힌 대로 쓴다.**

## 받는 것과 내는 것

- 받는 것: 맡은 묶음 파일 하나(25건). N번 묶음이면 \`${input('N')}\`
- 내는 것: **\`${output('N')}\`** 파일 하나. 묶음 파일 안의 \`output_path\` 와 같은 자리다.
${Array.from({ length: BATCH_COUNT }, (_, i) => `  - ${i + 1}번 묶음: \`${input(i + 1)}\` 를 읽고 → \`${output(i + 1)}\` 에 쓴다`).join('\n')}
  - 이 자리, 이 이름이어야 한다. 조립기가 여기만 읽는다. 다른 이름(\`batch-N.json.out.json\`, \`batch-N-out.json\` 등)이나 다른 폴더에 쓰지 않는다.
  - \`out\` 폴더가 없으면 만든다. 옛 파일이 있으면 덮어쓴다.
- 파일의 꼴: JSON 배열 하나. \`[{"id": "dev-001", "content": "원문 글"}, {"id": "test-014", "content": "…"}]\`
  - 25건 전부. \`id\` 는 받은 것 그대로. 열쇠는 \`id\` 와 \`content\` 둘뿐이다.
  - \`content\` 는 원문 글 하나다. 줄바꿈은 \`\\n\`, 탭은 \`\\t\` 로 넣는다. 설명이나 머리말, 코드 울타리를 붙이지 않는다.
  - 파일 전체가 \`JSON.parse\` 로 읽혀야 한다. 큰따옴표가 든 표기(예: \`15"\`)는 \`\\"\` 로 적는다.

## 읽어도 되는 것

- **이 안내와 맡은 묶음 파일, 둘뿐이다.**
- 다른 묶음 파일, 다른 이가 쓴 원문, 이 폴더와 윗폴더의 다른 파일(옛 원문, 설계도 모음, 분포표, 보고서), 프로젝트 저장소의 어떤 파일도 읽지 않는다.
  원문은 뽑는 쪽이 어떻게 생겼는지 모르고 써야 한다.

## 문서 한 건에 들어 있는 것

| 열쇠 | 뜻 |
|---|---|
| \`type_label\`, \`subtype\` | 무슨 상품인가 |
| \`style_label\` | 어떤 꼴로 쓸 것인가(아래 "꼴 다섯") |
| \`truth\` | 칸별 정답. 참고용이다. 원문에는 아래 표기로 쓴다 |
| \`surface_hints\` | 값이 있는 칸을 **원문에 어떤 표기로 쓸지** |
| \`absent\` | 값이 없는 칸. **원문에 쓰지 않는다** |
| \`must_include\` | 글자 그대로 넣을 문장 |
| \`notes\` | 이 건에만 해당하는 말 |

\`surface_hints\` 한 칸에는 이런 것이 있다.

| 열쇠 | 뜻 |
|---|---|
| \`label\` | 무슨 칸인가(양식의 칸 이름이다. 원문에 이 이름을 그대로 베끼지 않는다) |
| \`show\` | 원문에 적을 표기의 본보기 |
| \`tokens\` | **원문에 글자 그대로 들어가야 하는 조각들** |
| \`note\` | 이 표기를 쓸 때 지킬 것 |
| \`unit\`, \`declare_unit\` | 수 옆에 단위를 붙이지 않는 표기일 때 그 단위와, 글 다른 곳에 밝힐지 여부 |
| \`form\`, \`parts\` | 표기 꼴의 이름. 읽지 않아도 된다 |

## 꼭 지킬 것

1. **\`tokens\` 는 하나도 빠짐없이, 글자 그대로, 한 번 이상 원문에 들어간다.** 복사해서 붙인다.
   - 띄어쓰기, 쉼표, 기호(\`×\` \`x\` \`X\` \`*\` \`~\` \`-\` \`–\` \`→\` \`/\` \`|\` \`·\`), 전각 글자(\`￦\`), 대소문자까지 같아야 한다.
     비슷한 다른 기호로 바꾸지 않는다(\`×\` 를 \`x\` 로, \`~\` 를 \`-\` 로, \`만 원\` 을 \`만원\` 으로 바꾸면 틀린다).
   - 단위를 바꾸지 않는다. "8000mm" 를 "8m" 로, "오전 5시부터 다음날 새벽 1시까지" 를 "05시~25시" 로, "2주" 를 "14일" 로, "월 250만 명" 을 하루 값으로 고쳐 적지 않는다.
   - **같은 값을 다른 표기로 한 번 더 적지 않는다**(예: "150만원(1,500,000원)", "D-7(일주일 전)" 금지).
   - \`tokens\` 가 하나이고 \`show\` 와 같으면 그 표기를 통째로 쓴다. 앞뒤에 말을 붙이는 것은 된다(예: \`show\` "240회/일" → "송출은 240회/일 입니다").
   - \`tokens\` 가 \`show\` 의 한 토막이면(날짜 칸이 그렇다. 예: \`show\` "소재는 게재 7일 전까지", \`tokens\` ["7일 전까지"]) 토막만 글자 그대로 넣고 앞뒤 말은 자유롭게 쓴다.
     다만 그 날짜가 어느 칸의 것인지(소재 마감인지, 환불 기한인지, 예약 마감인지) 읽으면 알 수 있어야 한다.
   - \`tokens\` 가 여럿이면(값표, 가로·세로를 따로 적는 꼴) 전부 넣는다. 값표는 \`show\` 의 차례와 짝을 지킨다. 조각 사이의 줄바꿈과 구분은 \`note\` 를 따른다.
   - 두 칸의 조각이 같은 글자일 수 있다(예: 환불도 "7일 전까지", 예약도 "7일 전까지"). 그러면 칸마다 한 번씩, 두 번 쓴다.
   - 영어·중국어로 된 조각도 옮기지 않고 그대로 넣는다. 한국어로 된 조각을 영어·중국어로 옮기지도 않는다.
2. **\`note\` 를 따른다.** "월 단위라는 것을 밝힌다", "세로를 먼저 적는다", "짝마다 줄을 바꿔 적는다" 같은 말이 적혀 있다.
3. **\`unit\` 이 있는 칸은 수 옆에 단위를 붙이지 않는다.** \`declare_unit\` 이 \`true\` 면 그 단위를 글 다른 곳에 꼭 한 번 밝힌다
   (칸 이름·표 머리·문장. 예: "규격(m)", "단가(만원)", "※ 금액 단위: 천원"). \`declare_unit\` 이 \`false\` 면 단위를 어디에도 밝히지 않는다.
4. **\`absent\` 의 칸에 해당하는 정보는 원문 어디에도 쓰지 않는다.** 짐작해서 채우지 않는다.
   - \`how\` 가 \`omit\` 이면 그 칸 얘기를 아예 꺼내지 않는다.
   - \`how\` 가 \`placeholder\` 이면 칸 이름은 쓰고 값 자리에 \`placeholder\` 의 말만 쓴다(예: "소재 마감: 추후 안내").
   - 묶음 파일에 없는 칸(그 종류의 상품에 원래 없는 정보)도 지어내 넣지 않는다.
5. **정답에 없는 값을 지어내 넣지 않는다.** 다른 금액, 다른 크기, 다른 기간, 다른 시간, 다른 수량, 다른 날짜 수를 넣으면 정답이 흐려진다.
   - 설치비, 할인 금액, 할인율, 옆 지면의 값, "평소에는 ○○원", 문의 가능 시간, 담당자 근무 시간 같은 것을 넣지 않는다.
   - 칸과 상관없는 것은 된다: 인사, 매체 분위기, 주의할 점, 문의 방법, 가상의 담당자 이름.
6. **위치(\`region\`)와 출장 지역(\`service_region\`)은 정답 글자 그대로 한 번은 나오게 쓴다.**
   - 정답이 "강남역"이면 원문 어딘가에 "강남역"이 그것만으로 읽히게 나와야 한다(예: "위치: 강남역", "강남역에 있는 전광판입니다").
   - 더 자세한 설명(출구 번호, 층, 건물, 방향)을 붙이고 싶으면 **정답 글자와 떨어뜨려** 다른 문장이나 다른 칸에 쓴다.
     되는 예: "위치: 강남역" + 다른 줄에 "11번 출구에서 걸어서 1분". 안 되는 예: "위치: 강남역 11번 출구 앞 건물 외벽"(어디까지가 위치인지 정답보다 길게 읽힌다).
   - 다른 역·동네 이름을 위치처럼 읽히게 더 붙이지 않는다.
7. **이름은 지어낸 것만 쓴다.** 실제 가수, 그룹, 기획사, 회사, 상표를 쓰지 않는다. 마켓 이름이 필요하면 "응원장터"만 쓴다.
   전화번호와 계정은 "02-000-0000", "@example" 처럼 가짜임이 분명한 꼴로 쓴다. 지하철역과 동네 이름은 실제 지명 그대로 쓴다.
8. **길이는 100자에서 900자 사이.**
9. \`must_include\` 의 문장은 글자 그대로 넣는다. 그 문장이 값을 바꾸라고 해도 나머지 글은 정답대로 쓴다.
10. \`type_label\` 이 "등록 대상 아님"인 건은 상품 소개 글이 아니다. \`notes\` 의 주제로 짧은 글을 쓴다.

## 건마다 뼈대와 문장 틀이 달라야 한다

지난 차례의 검토에서 "같은 틀에 값만 갈아 끼운 글"이라는 말을 들었다. 이번에는 **25건이 스물다섯 사람이 쓴 것처럼** 보여야 한다.

- **뼈대**: 무엇부터 말하는지, 값이 어디에 놓이는지, 문단이 몇 개인지, 목록인지 줄글인지가 건마다 달라야 한다.
  "인사 → 상품 이름 → 크기 → 값 → 마감 → 문의" 같은 한 가지 차례를 되풀이하지 않는다. 값부터 꺼내는 글, 주의할 점부터 꺼내는 글, 질문에 답하는 글, 지난번 메일에 이어 쓰는 글이 섞여야 한다.
- **문장 틀**: 같은 칸을 같은 문장으로 두 번 쓰지 않는다. "소재는 게재 N일 전까지 보내 주세요"를 한 번 썼으면 다음 건은 다른 말로 쓴다.
  \`show\` 의 앞뒤 말은 본보기일 뿐이다. 그대로 베끼기보다 그 건의 글투에 맞게 바꾼다(조각은 그대로).
- **칸을 부르는 말**: 공급처마다 다르다. "규격·사이즈·크기·화면 크기", "단가·광고료·게재료·금액·비용", "송출 횟수·노출·편성". 양식의 칸 이름(\`label\`)을 그대로 쓰지 않는다. 칸 이름 없이 문장에 녹여도 된다.
- **쓰는 사람**: 영업 담당, 대표, 신입 사원, 대행사 직원, 자동 견적 메일. 말투와 꼼꼼함이 다르다. 오타까지 흉내 낼 필요는 없지만 군더더기, 줄임말, 덧붙이는 말은 건마다 다르게 둔다.
- 다 쓴 뒤 25건의 첫 문장과 끝 문장만 모아서 읽어 본다. 닮은 것이 있으면 고친다.

## 꼴 다섯

- **자유 글 공지**: 공급처가 게시판이나 메일에 올리는 안내 글. 문단으로 쓴다. 존댓말.
- **메신저 말투**: 담당자가 메신저로 보낸 듯한 짧은 줄 여러 개. 줄임말, 물결표, "넵", "~요" 같은 말투. 순서가 뒤죽박죽이어도 된다.
- **표 붙여 넣기**: 엑셀이나 문서의 표를 그대로 붙인 꼴. 탭이나 \`|\` 로 나뉜 줄, "항목 / 내용" 두 칸, 또는 "항목: 값" 줄. 표의 생김새(가로로 긴 표, 세로로 긴 표, 머리 줄이 있는 표와 없는 표)도 건마다 다르게 한다.
- **중국어·영어가 섞인 글**: 설명 문장을 중국어 간체와 영어로 섞어 쓴다. 한국어 문장도 조금 섞여도 된다. **조각은 적힌 글자 그대로 넣는다**(한국어 조각은 한국어로, 영어·중국어 조각은 그 말로).
- **여러 정보가 뒤섞인 긴 글**: 600~900자. 회사 소개, 인사, 진행 순서, 주의할 점, 문의 방법 사이사이에 값이 흩어져 있다. 값이 한곳에 모여 있지 않게 쓴다.

## 다 쓴 뒤 스스로 확인

- 25건이 모두 있는가. \`id\` 가 받은 것과 같은가.
- 건마다 \`tokens\` 가 전부 원문에 글자 그대로 있는가(눈으로 보지 말고 글자 찾기로 확인한다).
- \`unit\` 이 있는 칸: 수 옆에 단위가 안 붙었는가. \`declare_unit\` 대로 밝혔는가(또는 안 밝혔는가).
- \`absent\` 칸의 정보가 새어 들어가지 않았는가.
- 정답에 없는 금액·크기·기간·시간·수량이 없는가. 같은 값을 다른 표기로 또 적지 않았는가.
- 위치가 정답 글자 그대로 한 번 나오는가. 자세한 설명이 정답 글자에 붙어 있지 않은가.
- 길이가 100~900자인가.
- 결과 파일이 \`output_path\` 자리에 있고 JSON 으로 읽히는가.
`;
}
